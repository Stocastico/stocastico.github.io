#!/usr/bin/env node
'use strict';

/*
  generate-world-map.js

  Builds the lightweight inline SVG world map shown in the homepage "Places"
  teaser. Countries Stefano has lived in / visited are tagged with CSS classes
  (`wm-lived` / `wm-visited`); the actual colours come from CSS palette vars in
  css/styles.css, so switching the palette flows through automatically and this
  generator only needs to re-run when the COUNTRY LIST changes.

  Inputs:
    - data/countries-110m.json  (world-atlas TopoJSON, names + geometry)
    - data/countries.js         (generated by generate-countries.js: COUNTRIES)

  Output:
    - rewrites the marked block in index.html (between the BLOCK markers).

  Projection: plain equirectangular (x = lon, y = -lat); the viewBox is fitted
  to the data bounds. Coordinates are rounded to 1 decimal (~11 km) — plenty
  for a small decorative map and keeps the inline markup compact.
*/

const fs = require('node:fs');
const path = require('node:path');

const BLOCK_START = '<!-- world-map:start (generated by scripts/generate-world-map.js - do not edit) -->';
const BLOCK_END = '<!-- world-map:end -->';

function escapeAttr(value) {
  return String(value)
    .replace(/&/g, '&amp;')
    .replace(/"/g, '&quot;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;');
}

/* Decode every arc of the TopoJSON into absolute [lon, lat] coordinate lists. */
function makeArcDecoder(topo) {
  const { scale, translate } = topo.transform;
  return function decodeArc(idx) {
    const rev = idx < 0;
    const raw = topo.arcs[rev ? ~idx : idx];
    let cx = 0;
    let cy = 0;
    const pts = raw.map(([dx, dy]) => {
      cx += dx;
      cy += dy;
      return [cx * scale[0] + translate[0], cy * scale[1] + translate[1]];
    });
    return rev ? pts.slice().reverse() : pts;
  };
}

/* Concatenate the arcs of one ring into a single coordinate list. */
function ringCoords(arcIdxList, decodeArc) {
  const ring = [];
  for (const arcIdx of arcIdxList) {
    const pts = decodeArc(arcIdx);
    // Adjacent arcs share an endpoint; drop the duplicate join vertex.
    if (ring.length) ring.push(...pts.slice(1));
    else ring.push(...pts);
  }
  return ring;
}

/* Make a ring's longitudes continuous: when consecutive points jump by more
   than 180° they're really crossing the antimeridian, so unwrap by ±360°.
   Without this, an equirectangular projection stretches the segment clear
   across the map (Russia/Chukotka, Fiji). Mirrors the fix in js/globe.js. */
function unwrapRing(coords) {
  if (!coords.length) return coords;
  const out = [[coords[0][0], coords[0][1]]];
  for (let i = 1; i < coords.length; i += 1) {
    let lon = coords[i][0];
    const prevLon = out[i - 1][0];
    while (lon - prevLon > 180) lon -= 360;
    while (lon - prevLon < -180) lon += 360;
    out.push([lon, coords[i][1]]);
  }
  return out;
}

/* Build the SVG subpath(s) for one ring. Equirectangular projection
   (x = lon, y = -lat), rounded to 1 decimal. The ring is unwrapped first;
   when the unwrapped ring spills past ±180° we also emit a copy shifted by
   ∓360° so the wrapped-around piece still appears — the fixed viewBox clips
   whatever falls outside [-180, 180]. Updates `latBounds` (latitudes are
   never wrapped, so they're safe to use for the vertical extent). */
function ringSubpaths(coords, round, latBounds) {
  if (coords.length < 2) return [];
  const unwrapped = unwrapRing(coords);
  let minLon = Infinity;
  let maxLon = -Infinity;
  for (const [lon] of unwrapped) {
    if (lon < minLon) minLon = lon;
    if (lon > maxLon) maxLon = lon;
  }

  const subpathAt = (shift) => {
    let d = '';
    let prevX = null;
    let prevY = null;
    let emitted = 0;
    for (const [lon, lat] of unwrapped) {
      const x = round(lon + shift);
      const y = round(-lat);
      // Skip points that collapse onto the previous one after rounding.
      if (x === prevX && y === prevY) continue;
      prevX = x;
      prevY = y;
      if (lat < latBounds.min) latBounds.min = lat;
      if (lat > latBounds.max) latBounds.max = lat;
      // Compact path data: a leading minus is self-delimiting, so only emit a
      // space separator before a non-negative y.
      const sep = y < 0 ? '' : ' ';
      d += `${emitted === 0 ? 'M' : 'L'}${x}${sep}${y}`;
      emitted += 1;
    }
    return emitted >= 2 ? `${d}Z` : '';
  };

  const subs = [];
  const base = subpathAt(0);
  if (base) subs.push(base);
  if (maxLon > 180) {
    const wrapped = subpathAt(-360);
    if (wrapped) subs.push(wrapped);
  }
  if (minLon < -180) {
    const wrapped = subpathAt(360);
    if (wrapped) subs.push(wrapped);
  }
  return subs;
}

/* Build an SVG path `d` (one country, all polygons + holes). Returns null when
   the geometry has no drawable rings. Mutates `latBounds`. With
   `skipAntarctica`, rings lying entirely south of 55°S are dropped — Antarctica
   is irrelevant to a "places visited" map and its polar ring would otherwise
   need pole-bridging to fill correctly. */
function geometryToPath(geom, decodeArc, round, latBounds, opts = {}) {
  const polys = geom.type === 'Polygon' ? [geom.arcs] : geom.arcs;
  const segments = [];
  for (const poly of polys || []) {
    for (const ringArcs of poly) {
      const coords = ringCoords(ringArcs, decodeArc);
      if (coords.length < 2) continue;
      if (opts.skipAntarctica) {
        let maxLat = -Infinity;
        for (const p of coords) if (p[1] > maxLat) maxLat = p[1];
        if (maxLat < -55) continue;
      }
      segments.push(...ringSubpaths(coords, round, latBounds));
    }
  }
  return segments.length ? segments.join('') : null;
}

/* Builds the homepage map: one grey silhouette path for the whole world
   (`wm-land`), then one filled path per highlighted country on top
   (`wm-lived` / `wm-visited`). Non-highlighted countries are not drawn
   individually — they live in the silhouette — which keeps the markup small
   and the teaser uncluttered. Fills come from CSS palette vars (see
   css/styles.css), so palette switches need no regeneration here. */
function buildWorldMapSvg(topo, countries) {
  const lived = new Set((countries && countries.lived) || []);
  const visited = new Set((countries && countries.visited) || []);
  const decodeArc = makeArcDecoder(topo);

  // Equirectangular; round to 1 decimal place. Only latitudes feed the
  // viewBox — longitude is fixed to the full [-180, 180] world so wrapped
  // (antimeridian) overflow is clipped cleanly at the date line.
  const round = (n) => Math.round(n * 10) / 10;
  const latBounds = { min: Infinity, max: -Infinity };

  // Base silhouette — the merged land object covers the full extent.
  const land = topo.objects.land.geometries[0];
  const landPath = geometryToPath(land, decodeArc, round, latBounds, { skipAntarctica: true });

  // Highlighted countries painted over the silhouette.
  const highlights = [];
  for (const geom of topo.objects.countries.geometries) {
    const name = (geom.properties && geom.properties.name) || '';
    const isLived = lived.has(name);
    const isVisited = visited.has(name);
    if (!isLived && !isVisited) continue;
    const d = geometryToPath(geom, decodeArc, round, latBounds, { skipAntarctica: true });
    if (!d) continue;
    const cls = `wm-country ${isLived ? 'wm-lived' : 'wm-visited'}`;
    highlights.push(`<path class="${cls}" data-name="${escapeAttr(name)}" d="${d}"/>`);
  }

  const padY = 2;
  const minX = -180;
  const w = 360;
  const minY = round(-latBounds.max - padY);
  const h = round(latBounds.max - latBounds.min + padY * 2);

  return (
    `<svg class="world-map" viewBox="${minX} ${minY} ${w} ${h}" ` +
    'role="img" aria-labelledby="world-map-title" preserveAspectRatio="xMidYMid meet" ' +
    'xmlns="http://www.w3.org/2000/svg">' +
    '<title id="world-map-title">World map highlighting countries Stefano has lived in or visited</title>' +
    `<path class="wm-land" d="${landPath}"/>` +
    highlights.join('') +
    '</svg>'
  );
}

function replaceBlock(html, inner) {
  const startIdx = html.indexOf(BLOCK_START);
  const endIdx = html.indexOf(BLOCK_END);
  if (startIdx === -1 || endIdx === -1 || endIdx < startIdx) {
    throw new Error(`Could not find world-map markers (${BLOCK_START} … ${BLOCK_END})`);
  }
  const before = html.slice(0, startIdx + BLOCK_START.length);
  const after = html.slice(endIdx);
  return `${before}\n${inner}\n          ${after}`;
}

function parseArgs(argv) {
  const out = {
    topo: 'data/countries-110m.json',
    countries: 'data/countries.js',
    target: 'index.html',
    dryRun: false,
  };
  for (let i = 2; i < argv.length; i += 1) {
    const arg = argv[i];
    if (arg === '--topo') out.topo = argv[++i];
    else if (arg === '--countries' || arg === '-c') out.countries = argv[++i];
    else if (arg === '--target' || arg === '-t') out.target = argv[++i];
    else if (arg === '--dry-run') out.dryRun = true;
    else if (arg === '--help' || arg === '-h') out.help = true;
    else throw new Error(`Unknown argument: ${arg}`);
  }
  return out;
}

function printHelp() {
  console.log(`Usage:
  node scripts/generate-world-map.js [options]

Rebuilds the inline SVG world map block in index.html from the country list.

Options:
      --topo <path>       TopoJSON source (default: data/countries-110m.json)
  -c, --countries <path>  countries.js module (default: data/countries.js)
  -t, --target <path>     HTML file to rewrite (default: index.html)
      --dry-run           print the SVG without writing the file
  -h, --help              show this help
`);
}

/* Read COUNTRIES out of the generated ESM module without importing it (this
   script is CJS). The module is a plain `export const COUNTRIES = { ... }`. */
function readCountriesModule(filePath) {
  const src = fs.readFileSync(filePath, 'utf8');
  const m = src.match(/export const COUNTRIES =\s*(\{[\s\S]*?\});/);
  if (!m) throw new Error(`Could not parse COUNTRIES from ${filePath}`);
  // eslint-disable-next-line no-new-func
  return Function(`return (${m[1]})`)();
}

function main() {
  const options = parseArgs(process.argv);
  if (options.help) {
    printHelp();
    return;
  }

  const topoPath = path.resolve(options.topo);
  const countriesPath = path.resolve(options.countries);
  const targetPath = path.resolve(options.target);

  const topo = JSON.parse(fs.readFileSync(topoPath, 'utf8'));
  const countries = readCountriesModule(countriesPath);
  const svg = buildWorldMapSvg(topo, countries);

  if (options.dryRun) {
    console.log(svg);
    console.log(`\n(${(svg.length / 1024).toFixed(1)} KB)`);
    return;
  }

  const html = fs.readFileSync(targetPath, 'utf8');
  const updated = replaceBlock(html, svg);
  fs.writeFileSync(targetPath, updated, 'utf8');
  console.log(`Updated world-map block in ${path.relative(process.cwd(), targetPath)} (${(svg.length / 1024).toFixed(1)} KB SVG)`);
}

if (require.main === module) {
  try {
    main();
  } catch (err) {
    console.error(`Error: ${err.message}`);
    process.exitCode = 1;
  }
}

module.exports = {
  buildWorldMapSvg,
  geometryToPath,
  makeArcDecoder,
  replaceBlock,
  readCountriesModule,
  BLOCK_START,
  BLOCK_END,
};
